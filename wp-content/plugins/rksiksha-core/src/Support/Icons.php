	public static function svg( string $name, int $size = 18, string $extra_class = '' ): string {
		$path = self::PATHS[ $name ] ?? '';
		if ( '' === $path ) return '';
		$class = trim( 'rks-icon ' . $extra_class );
		return sprintf(
			'<svg class="%s" xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">%s</svg>',
			esc_attr( $class ),
			$size,
			$size,
			$path
		);
	}

	/**
	 * Modern "chip" icon — sits in a tinted rounded square container.
	 * Tones: red, mint, teal, gold, slate, lilac, lime, sky.
	 */
	public static function chip( string $name, string $tone = 'teal', int $size = 18 ): string {
		$tone = preg_match( '/^[a-z]+$/', $tone ) ? $tone : 'teal';
		return sprintf(
			'<span class="rks-icon-chip rks-icon-chip--%s">%s</span>',
			esc_attr( $tone ),
			self::svg( $name, $size )
		);
	}

	/** Returns true if an icon name is registered. */
	public static function exists( string $name ): bool {
		return isset( self::PATHS[ $name ] );
	}
